// Promote reviewed staging candidates to gallery4/5/6.webp.
//
// After contact-sheet review, write staging/picks.json:
//   { "tet-nguyen-dan": [2, 4, 7], ... }   — cand-N numbers, exactly 3 each
// then run:  node scripts/promote-gallery.mjs
//
// For every slug with picks: re-encodes cand-N.webp -> gallery4/5/6.webp at
// 960w q74, then merges new credit rows into src/data/image-credits.ts and
// public/images/CREDITS.md (same writer logic as fetch-images.mjs).
import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const STAGE = "staging";
const OUT = "public/images/holidays";
const PICKS = join(STAGE, "picks.json");

if (!existsSync(PICKS)) {
  console.error(`missing ${PICKS} — write { slug: [cand#, cand#, cand#] } after review`);
  process.exit(1);
}
const picks = JSON.parse(readFileSync(PICKS, "utf8"));

// Merge with every credit already on the site (same trick as --fill).
const credits = {};
if (existsSync("src/data/image-credits.ts")) {
  const m = readFileSync("src/data/image-credits.ts", "utf8").match(
    /imageCredits: Record<string, ImageCredit\[]> = ([\s\S]*);\s*$/,
  );
  if (m) Object.assign(credits, JSON.parse(m[1]));
}

let promoted = 0;
const problems = [];
for (const slug of readdirSync(STAGE)) {
  if (slug === "picks.json") continue;
  const chosen = picks[slug];
  if (!chosen) continue;
  const dir = join(STAGE, slug);
  const manifestFile = join(dir, "manifest.json");
  if (!existsSync(manifestFile)) {
    problems.push(`${slug}: no manifest`);
    continue;
  }
  const manifest = JSON.parse(readFileSync(manifestFile, "utf8"));
  const byFile = Object.fromEntries(manifest.map((m) => [m.file, m]));
  if (chosen.length !== 3) {
    problems.push(`${slug}: needs exactly 3 picks, got ${chosen.length}`);
    continue;
  }
  const bases = ["gallery4", "gallery5", "gallery6"];
  for (let i = 0; i < 3; i++) {
    const candFile = `cand-${chosen[i]}.webp`;
    const entry = byFile[candFile];
    const src = join(dir, candFile);
    if (!entry || !existsSync(src)) {
      problems.push(`${slug}: missing ${candFile}`);
      continue;
    }
    const dst = join(OUT, slug, `${bases[i]}.webp`);
    await sharp(readFileSync(src))
      .resize(960, null, { withoutEnlargement: true })
      .webp({ quality: 74 })
      .toFile(dst);
    // Replace any stale credit for this slot, then append the new one.
    const slot = `${slug}/${bases[i]}.webp`;
    credits[slug] = (credits[slug] ?? []).filter((c) => c.file !== slot);
    credits[slug].push({
      file: slot,
      photographer: entry.photographer,
      profile: entry.profile,
      photo: entry.photo,
      license: entry.license,
      source: entry.source,
      alt: entry.alt.slice(0, 120),
    });
    promoted++;
    console.log(`${slot} <- ${candFile}  (${entry.license})`);
  }
}

const ts = `// AUTO-GENERATED by scripts/fetch-images.mjs — do not edit by hand.
export interface ImageCredit {
  file: string;
  photographer: string;
  profile: string;
  photo: string;
  license: string;
  source: string;
  alt: string;
}
export const imageCredits: Record<string, ImageCredit[]> = ${JSON.stringify(credits, null, 2)};
`;
writeFileSync("src/data/image-credits.ts", ts);
const md = [
  "# Image credits",
  "",
  "Photos from Wikimedia Commons contributors; see per-file license and description pages.",
  "",
  "| File | Author | License | Source |",
  "|---|---|---|---|",
  ...Object.values(credits)
    .flat()
    .map((c) => `| ${c.file} | ${c.photographer} | ${c.license} | [Commons](${c.photo}) |`),
  "",
].join("\n");
writeFileSync("public/images/CREDITS.md", md);

console.log(`\npromoted=${promoted}`);
if (problems.length) {
  console.log("PROBLEMS:");
  problems.forEach((p) => console.log("  " + p));
}
