// Derivative generator:
//  • writes 480w variants of card.webp / galleryN.webp (grids serve a
//    right-sized image via srcset instead of the full 800px file)
//  • writes every hero-<w>.webp ladder rung that is NOT larger than the
//    source hero.webp, and emits src/data/hero-sizes.ts with each slug's
//    real source width so HImg's srcset only advertises files that exist
//    (and always offers the original as the top rung).
// Idempotent: missing or wrong-size files are (re)written.
// Run: node scripts/gen-thumbs.mjs
import {
  existsSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const DIR = "public/images/holidays";
const THUMB_W = 480;
const HERO_WIDTHS = [480, 800, 1200, 1600];

let written = 0;
const heroSizes = {};
for (const slug of readdirSync(DIR)) {
  const dir = join(DIR, slug);
  if (!statSync(dir, { throwIfNoEntry: false })?.isDirectory()) continue;
  for (const base of ["card", "gallery1", "gallery2", "gallery3"]) {
    const src = join(dir, `${base}.webp`);
    const dst = join(dir, `${base}-${THUMB_W}.webp`);
    if (!existsSync(src) || existsSync(dst)) continue;
    await sharp(readFileSync(src))
      .resize(THUMB_W, null, { withoutEnlargement: true })
      .webp({ quality: 80 })
      .toFile(dst);
    written++;
  }
  const hero = join(dir, "hero.webp");
  if (existsSync(hero)) {
    const { width: srcW } = await sharp(readFileSync(hero)).metadata();
    heroSizes[slug] = srcW;
    for (const w of HERO_WIDTHS) {
      if (w > srcW) continue; // never upscale / never lie about width
      const dst = join(dir, `hero-${w}.webp`);
      let ok = false;
      if (existsSync(dst)) {
        const m = await sharp(readFileSync(dst)).metadata();
        ok = m.width === w;
      }
      if (ok) continue;
      const buf = await sharp(readFileSync(hero))
        .resize(w, null, { withoutEnlargement: true })
        .webp({ quality: 78 })
        .toBuffer();
      writeFileSync(dst, buf);
      written++;
    }
  }
}

const ts =
  `// GENERATED by scripts/gen-thumbs.mjs — real pixel width of each\n` +
  `// holiday's hero.webp source. Used to build honest srcset ladders.\n` +
  `export const HERO_SRC_W: Record<string, number> = ${JSON.stringify(heroSizes, null, 2)};\n`;
writeFileSync("src/data/hero-sizes.ts", ts);
console.log(`gen-thumbs: wrote ${written} derivative files + hero-sizes.ts`);
